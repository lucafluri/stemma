let currentLang = localStorage.getItem('gedcomVisLang') || 'en';

function _getDictPath(dict, path) {
  const parts = path.split('.');
  let cur = dict;
  for (const p of parts) {
    if (cur == null || typeof cur !== 'object') return undefined;
    cur = cur[p];
  }
  return cur;
}

function t(key, vars = {}) {
  const value = _getDictPath(I18N[currentLang], key) ?? _getDictPath(I18N.de, key) ?? key;
  if (typeof value !== 'string') return key;
  return value.replace(/\$\{(\w+)\}/g, (_, name) => {
    if (name in vars) return vars[name];
    return '';
  });
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('gedcomVisLang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  if (window._onLanguageChanged) window._onLanguageChanged(lang);
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (val !== key) {
      if (el.tagName === 'TITLE') document.title = val;
      else el.textContent = val;
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    const val = t(key);
    if (val !== key) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    const val = t(key);
    if (val !== key) el.title = val;
  });
  // A control whose only name is an aria-label needs that label translated too,
  // or the screen reader keeps reading it out in the language the page left.
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.dataset.i18nAria;
    const val = t(key);
    if (val !== key) el.setAttribute('aria-label', val);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const val = t(key);
    if (val !== key) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-label]').forEach(el => {
    const key = el.dataset.i18nLabel;
    const val = t(key);
    if (val !== key) el.setAttribute('aria-label', val);
  });
  const langSwitcher = document.getElementById('lang-switcher');
  if (langSwitcher) langSwitcher.value = currentLang;
}

document.documentElement.lang = currentLang;
applyTranslations();

window.t = t;
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;
window.getCurrentLang = () => currentLang;
